/// Sway codegen CLI — generates type-safe Dart from `.sway.json` files.
///
/// Usage: `dart run sway:codegen [--input <dir>] [--output <file>]`
library;

import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

void main(List<String> arguments) {
  String inputDir = 'lib/i18n';
  String outputFile = 'lib/i18n/sway.g.dart';

  for (var i = 0; i < arguments.length; i++) {
    switch (arguments[i]) {
      case '--input':
        if (i + 1 < arguments.length) inputDir = arguments[++i];
      case '--output':
        if (i + 1 < arguments.length) outputFile = arguments[++i];
      case '--help':
      case '-h':
        _printUsage();
        return;
    }
  }

  final dir = Directory(inputDir);
  if (!dir.existsSync()) {
    stderr.writeln('Error: input directory does not exist: $inputDir');
    exit(1);
  }

  final files = dir
      .listSync()
      .whereType<File>()
      .where((f) => f.path.endsWith('.sway.json'))
      .toList();

  if (files.isEmpty) {
    stderr.writeln(
      'Error: No .sway.json files found in ${dir.path}\n'
      'Create locale files like en.sway.json, ar.sway.json first.',
    );
    exit(1);
  }

  final buffer = StringBuffer();
  buffer.writeln('// GENERATED FILE — DO NOT EDIT');
  buffer.writeln('// Generated by Sway — To regenerate, run: dart run sway:codegen');
  buffer.writeln();
  buffer.writeln("import 'package:flutter/widgets.dart';");
  buffer.writeln();

  final langCodes = <String>[];

  for (final file in files) {
    final content = file.readAsStringSync();
    final data = json.decode(content) as Map<String, dynamic>;
    final langCode = p
        .basenameWithoutExtension(file.path)
        .replaceAll('.sway', '');
    final isRtl = {'ar', 'he', 'fa', 'ur', 'ps', 'sd', 'yi', 'dv', 'ckb'}
        .contains(langCode.toLowerCase());

    langCodes.add(langCode);
    _emitLocale(buffer, langCode, data, isRtl);
  }

  _emitRegistry(buffer, langCodes);

  final outFile = File(outputFile);
  outFile.parent.createSync(recursive: true);
  outFile.writeAsStringSync(buffer.toString());

  stdout.writeln('Generated: $outputFile');
  stdout.writeln('Locales: ${langCodes.join(', ')}');
}

/// Emits a flat locale class with getters for every key.
///
/// Keys are flattened with underscores: `home.welcome` → `homeWelcome`.
/// Nested objects become prefixed getters: `home.itemCount.one` → `homeItemCountOne`.
void _emitLocale(
  StringBuffer buffer,
  String langCode,
  Map<String, dynamic> data,
  bool isRtl,
) {
  final className = 'SwayTranslations${_toSuffix(langCode)}';

  buffer.writeln('/// Sway translations for locale: $langCode');
  buffer.writeln('class $className {');
  buffer.writeln('  /// Creates [$className].');
  buffer.writeln('  const $className();');
  buffer.writeln();
  buffer.writeln('  /// The locale this translations class is for.');
  buffer.writeln("  static const Locale locale = Locale('$langCode');");
  buffer.writeln();
  buffer.writeln('  /// Whether this locale is right-to-left.');
  buffer.writeln('  static const bool isRtl = $isRtl;');
  buffer.writeln();

  // Flatten all keys
  _emitFlatGetters(buffer, data, '', 2);

  buffer.writeln('}');
  buffer.writeln();
}

/// Recursively emits flat getters for all keys in a nested map.
void _emitFlatGetters(
  StringBuffer buffer,
  Map<String, dynamic> data,
  String prefix,
  int indent,
) {
  for (final entry in data.entries) {
    final key = entry.key;
    final path = prefix.isEmpty ? key : '$prefix$key';

    if (entry.value is String) {
      _emitStringGetter(buffer, path, entry.value as String, indent);
    } else if (entry.value is Map<String, dynamic>) {
      _emitFlatGetters(buffer, entry.value as Map<String, dynamic>, '${key}_', indent);
    }
  }
}

/// Emits a string getter with optional placeholder parameters.
void _emitStringGetter(
  StringBuffer buffer,
  String key,
  String value,
  int indent,
) {
  final pad = '  ' * indent;
  final methodName = _toCamelCase(key);
  final placeholders = RegExp(r'\{(\w+)\}').allMatches(value).toList();

  if (placeholders.isEmpty) {
    buffer.writeln('$pad/// `$value`');
    buffer.writeln("${pad}String get $methodName => '${_escape(value)}';");
  } else {
    final params = placeholders.map((m) {
      final name = m.group(1)!;
      final type = name == 'count' ? 'num' : 'String';
      return 'required $type $name';
    }).join(', ');

    var interpolated = value;
    for (final m in placeholders) {
      final name = m.group(1)!;
      interpolated = interpolated.replaceAll('{$name}', '\$$name');
    }

    buffer.writeln('$pad/// `$value`');
    buffer.writeln(
      "${pad}String $methodName({$params}) => '${_escape(interpolated)}';",
    );
  }
  buffer.writeln();
}

/// Emits the unified SwayTranslations registry.
void _emitRegistry(StringBuffer buffer, List<String> langCodes) {
  buffer.writeln('/// Unified translations registry.');
  buffer.writeln('///');
  buffer.writeln('/// Access translations via static fields:');
  buffer.writeln('/// ```dart');
  buffer.writeln('/// final t = SwayTranslations.en;');
  buffer.writeln('/// Text(t.appTitle);');
  buffer.writeln('/// Text(t.homeWelcome(name: "Dipesh"));');
  buffer.writeln('/// ```');
  buffer.writeln('class SwayTranslations {');
  buffer.writeln('  SwayTranslations._();');
  buffer.writeln();

  for (final code in langCodes) {
    final className = 'SwayTranslations${_toSuffix(code)}';
    buffer.writeln('  /// Translations for the `$code` locale.');
    buffer.writeln('  static const $className $code = $className();');
  }

  buffer.writeln();
  buffer.writeln('  /// All supported locales.');
  buffer.writeln('  static const List<Locale> supportedLocales = [');
  for (final code in langCodes) {
    buffer.writeln("    Locale('$code'),");
  }
  buffer.writeln('  ];');
  buffer.writeln('}');
}

String _toSuffix(String langCode) {
  return langCode
      .split('_')
      .map((p) => p[0].toUpperCase() + p.substring(1))
      .join();
}

/// Converts a dot/underscore-separated key to camelCase.
///
/// `home.welcome` → `homeWelcome`, `itemCount.one` → `itemCountOne`.
String _toCamelCase(String key) {
  final parts = key.split('_');
  if (parts.isEmpty) return key;
  return parts.first + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

String _escape(String s) {
  return s
      .replaceAll('\\', '\\\\')
      .replaceAll("'", "\\'")
      .replaceAll('\n', '\\n')
      .replaceAll('\r', '\\r')
      .replaceAll('\t', '\\t');
}

void _printUsage() {
  stdout.writeln('Sway Codegen CLI');
  stdout.writeln();
  stdout.writeln('Usage:');
  stdout.writeln('  dart run sway:codegen [options]');
  stdout.writeln();
  stdout.writeln('Options:');
  stdout.writeln('  --input <dir>     Directory with .sway.json files (default: lib/i18n)');
  stdout.writeln('  --output <file>   Output Dart file (default: lib/i18n/sway.g.dart)');
  stdout.writeln('  -h, --help        Show this help');
}
